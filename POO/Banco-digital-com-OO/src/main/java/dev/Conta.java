package main.java.dev;

// abstract > não permite a classe ser instanciada
public abstract class Conta implements IConta{

    private static final int AGENCIA_PADRAO = 1;
    // É um contador sequencia, ou seja a cada conta criada adiciona 1 numero de conta;
    private static int SEQUENCIAL = 1;
    private Cliente cliente; // Pode definir um constructor aonde cada Conta tem um Cliente relacionado a ela

    protected int agencia;
    protected int numero;
    protected double saldo;


    public Conta(Cliente cliente) {
        this.agencia = Conta.AGENCIA_PADRAO;
        this.numero = SEQUENCIAL++;
        this.cliente = cliente;
    }

    @Override
    public void sacar(double valor) {
        this.saldo -= valor;
    }

    @Override
    public void depositar(double valor) {
        this.saldo += valor;
    }

    @Override
    public void transferir(double valor, Conta contaDestino) {
        this.sacar(valor);
        contaDestino.depositar(valor);
    }

    public int getAgencia() {
        return agencia;
    }

    public int getNumero() {
        return numero;
    }

    public double getSaldo() {
        return saldo;
    }

    protected void imprimirExtrato() {
        System.out.println(String.format("Titular: %s", this.cliente.getNome()));
        System.out.println(String.format("Agencia: %d", this.agencia));
        System.out.println(String.format("Numero: %d", this.numero));
        System.out.println(String.format("Saldo: %.2f", this.saldo));
    }
}
